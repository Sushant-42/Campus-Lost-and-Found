-- CS543 Assignment 2: Campus/Student Lost & Found Management System
-- Target: PostgreSQL 14+. Each table has exactly one service owner.
-- Cross-service IDs are external references, not cross-service foreign keys.
-- Production deployment should isolate service-owned tables by database/schema.

CREATE TABLE users (
 user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('STUDENT','STAFF','ADMIN')),
 campus_id VARCHAR(50) UNIQUE, identity_verified BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Owner: User Service
CREATE TABLE profiles (
 profile_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL UNIQUE, phone VARCHAR(25), department VARCHAR(100),
 student_or_staff_id VARCHAR(50), updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Owner: User Service
CREATE TABLE categories (
 category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE, description VARCHAR(255)
);
-- Owner: Item Report Service
CREATE TABLE lost_items (
 lost_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reporter_id BIGINT NOT NULL, category_id BIGINT NOT NULL REFERENCES categories(category_id),
 title VARCHAR(150) NOT NULL, description TEXT NOT NULL, location VARCHAR(180) NOT NULL,
 lost_date DATE NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','MATCHED','CLAIM_PENDING','RESOLVED','CLOSED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Owner: Item Report Service; reporter_id is a User Service identifier.
CREATE TABLE found_items (
 found_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reporter_id BIGINT NOT NULL, category_id BIGINT NOT NULL REFERENCES categories(category_id),
 title VARCHAR(150) NOT NULL, description TEXT NOT NULL, location VARCHAR(180) NOT NULL,
 found_date DATE NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','CLAIM_PENDING','CLAIMED','RETURNED','CLOSED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Owner: Item Report Service; reporter_id is a User Service identifier.
CREATE TABLE matches (
 match_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lost_item_id BIGINT NOT NULL, found_item_id BIGINT NOT NULL,
 score NUMERIC(5,2) NOT NULL CHECK (score BETWEEN 0 AND 100),
 explanation TEXT NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'SUGGESTED' CHECK (status IN ('SUGGESTED','VIEWED','DISMISSED','CLAIM_STARTED','CONFIRMED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_match_pair UNIQUE (lost_item_id, found_item_id)
);
-- Owner: Matching Service; item IDs are external identifiers.
CREATE TABLE claims (
 claim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 claimant_id BIGINT NOT NULL, found_item_id BIGINT NOT NULL, proof_details TEXT NOT NULL,
 idempotency_key VARCHAR(100) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'SUBMITTED' CHECK (status IN ('SUBMITTED','UNDER_REVIEW','APPROVED','REJECTED','CANCELLED','COMPLETED')),
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_claim_idempotency UNIQUE (claimant_id, idempotency_key)
);
-- Owner: Claims & Verification Service.
CREATE UNIQUE INDEX uq_active_claim_per_user_item ON claims(claimant_id, found_item_id)
 WHERE status IN ('SUBMITTED','UNDER_REVIEW','APPROVED');
CREATE TABLE claim_verification (
 verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 claim_id BIGINT NOT NULL REFERENCES claims(claim_id) ON DELETE CASCADE,
 verified_by BIGINT NOT NULL, verification_notes TEXT,
 result VARCHAR(20) NOT NULL CHECK (result IN ('APPROVED','REJECTED','NEEDS_INFO')),
 verified_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Owner: Claims & Verification Service; verified_by is an external User Service identifier.
CREATE TABLE notifications (
 notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient_id BIGINT NOT NULL, notification_type VARCHAR(50) NOT NULL, message TEXT NOT NULL,
 related_entity_type VARCHAR(40), related_entity_id VARCHAR(100),
 is_read BOOLEAN NOT NULL DEFAULT FALSE,
 delivery_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (delivery_status IN ('PENDING','SENT','FAILED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Owner: Notification Service.
CREATE TABLE handovers (
 handover_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 claim_id BIGINT NOT NULL, meeting_location VARCHAR(180) NOT NULL, scheduled_at TIMESTAMPTZ NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED','CONFIRMED','COMPLETED','CANCELLED','MISSED')),
 created_by BIGINT NOT NULL, confirmed_by BIGINT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_handover_time CHECK (scheduled_at > created_at)
);
-- Owner: Notification Service; claim_id and user IDs are external identifiers.

CREATE INDEX idx_lost_items_status_category ON lost_items(status, category_id);
CREATE INDEX idx_found_items_status_category ON found_items(status, category_id);
CREATE INDEX idx_lost_items_date ON lost_items(lost_date DESC);
CREATE INDEX idx_found_items_date ON found_items(found_date DESC);
CREATE INDEX idx_matches_status_score ON matches(status, score DESC);
CREATE INDEX idx_claims_status_date ON claims(status, submitted_at DESC);
CREATE INDEX idx_notifications_recipient_unread ON notifications(recipient_id, is_read, created_at DESC);
CREATE INDEX idx_handovers_scheduled_at ON handovers(scheduled_at);
